/// What the dispatcher knows before a command context exists.
#[derive(Debug)]
#[expect(
    dead_code,
    reason = "read by the W0-stub context builders, removed by WP-33"
)]
pub(crate) struct Cx<'a> {
    /// The brand of this invocation.
    pub(crate) brand: Brand,
    /// The startup environment.
    pub(crate) env: &'a Env,
    /// The process printer.
    pub(crate) printer: &'a Printer,
    /// The process cancel token (signals, EPIPE, panics).
    pub(crate) cancel: &'a CancelToken,
    /// `argv[0]` as given.
    pub(crate) arg0: Option<&'a OsStr>,
}

/// The dispatch table: `pre_commit.main.main`'s `if args.command == …` chain plus the snp-brand commands.
pub(crate) fn run(cli: Cli, cx: &Cx<'_>) -> Result<i32, Failure> {
    match cli {
        Cli::Run(a) => snp_run::run(a, &run_ctx(cx)?),
        Cli::TryRepo(a) => snp_run::try_repo(a, &run_ctx(cx)?),
        Cli::HookImpl(a) => snp_run::hook_impl(a, &mut std::io::stdin().lock(), &run_ctx(cx)?),
        Cli::InstallHooks(a) => snp_run::install_hooks(a, &run_ctx(cx)?),
        Cli::List(a) => snp_run::list(a, &run_ctx(cx)?),
        Cli::Install(a) => install(&a, cx),
        Cli::Uninstall(a) => with_cmd_ctx(cx, &|c| snp_cmd::uninstall(&a, c)),
        Cli::InitTemplatedir(a) => with_cmd_ctx(cx, &|c| snp_cmd::init_templatedir(&a, c)),
        Cli::Autoupdate(a) => with_cmd_ctx(cx, &|c| snp_cmd::autoupdate(&a, c)),
        Cli::Clean(_) => with_cmd_ctx(cx, &snp_cmd::clean),
        Cli::Gc(_) => with_cmd_ctx(cx, &snp_cmd::gc),
        Cli::MigrateConfig(a) => with_cmd_ctx(cx, &|c| snp_cmd::migrate_config(&a, c)),
        Cli::SampleConfig(_) => with_cmd_ctx(cx, &snp_cmd::sample_config),
        Cli::ValidateConfig(a) => with_cmd_ctx(cx, &|c| snp_cmd::validate_config(&a, c)),
        Cli::ValidateManifest(a) => with_cmd_ctx(cx, &|c| snp_cmd::validate_manifest(&a, c)),
        Cli::Hazmat(a) => snp_hooks::hazmat::cli(&a.tool, cx.env, cx.cancel),
        Cli::Config(a) => with_cmd_ctx(cx, &|c| snp_cmd::config(&a, c)),
        Cli::Cache(a) => with_cmd_ctx(cx, &|c| snp_cmd::cache(&a, c)),
        Cli::Migrate(a) => migrate(&a, cx),
        Cli::Doctor(a) => doctor(&a, cx),
        Cli::SelfCmd(a) => with_cmd_ctx(cx, &|c| snp_cmd::self_cmd(&a, c)),
        Cli::Completions(shell) => Ok(completions(shell, cx.printer)),
        _ => Err(Failure::unexpected(
            "NotImplementedError",
            "command not wired into the dispatch table",
        )),
    }
}

/// `install` then, with `--install-hooks`, `install_hooks` (pre-commit's order; the first failure wins, ADR-070).
fn install(a: &InstallArgs, cx: &Cx<'_>) -> Result<i32, Failure> {
    let code = with_cmd_ctx(cx, &|c| snp_cmd::install(a, c))?;
    if code != 0 || !a.install_hooks {
        return Ok(code);
    }
    let hooks = InstallHooksArgs {
        color: a.color,
        config: a.config.clone(),
        with_fallback: false,
    };
    snp_run::install_hooks(hooks, &run_ctx(cx)?)
}

/// `completions <shell>`: the script generated by `xtask completions` (`snp_cli::COMPLETIONS`).
fn completions(shell: Shell, printer: &Printer) -> i32 {
    let wanted = std::mem::discriminant(&shell);
    match snp_cli::COMPLETIONS
        .iter()
        .find(|(s, _)| std::mem::discriminant(s) == wanted)
    {
        Some((_, script)) => {
            printer.write(script.as_bytes());
            0
        }
        None => 1,
    }
}

