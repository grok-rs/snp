/// The oracle directory as testkit locates it: `SNP_ORACLE_DIR`, else `target/oracle`.
fn oracle_dir() -> PathBuf {
    snp_core::env::Env::capture_process()
        .get("SNP_ORACLE_DIR")
        .map(std::ffi::OsStr::to_os_string)
        .map_or_else(
            || Path::new(env!("CARGO_MANIFEST_DIR")).join("../../target/oracle"),
            PathBuf::from,
        )
}

/// The pc462-py312 oracle, or `None` (the M11-MIG interop rows are skipped, with a notice on stderr) when it is not
/// installed. `SNP_REQUIRE_ORACLE=1` (set by the job that runs `cargo xtask oracle install`) makes a missing oracle
/// a failure, so the interop rows can never pass vacuously there.
#[track_caller]
fn oracle_cmd(env: &TestEnv, cwd: &Path) -> Option<snp_testkit::Cmd> {
    let cmd = env.oracle(Oracle::Pc462Py312, cwd);
    if cmd.is_none() {
        let required = snp_core::env::Env::capture_process()
            .get("SNP_REQUIRE_ORACLE")
            .is_some_and(|v| v == "1");
        assert!(
            !required,
            "SNP_REQUIRE_ORACLE=1 but no oracle at {}",
            oracle_dir().join("pc462-py312").display()
        );
        eprintln!(
            "SKIPPED ({}): pre-commit oracle not installed (cargo xtask oracle install)",
            std::panic::Location::caller()
        );
    }
    cmd
}

