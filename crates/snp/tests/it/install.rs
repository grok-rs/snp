/// Every embedded token survives `sh` word splitting byte for byte (posix).
#[cfg(unix)]
#[test]
fn rendered_tokens_round_trip_through_sh() {
    use std::os::unix::ffi::OsStrExt;
    let env = tenv();
    let dir = env.root().join("rt");
    std::fs::create_dir_all(&dir).unwrap();
    let configs: [&[u8]; 6] = [
        b"my cfg's.yaml",
        b"a\"b$c`d\\e.yaml",
        b"--weird.yaml",
        b"\xff\xfe non utf8.yaml",
        b"*?[].yaml",
        b"new\nline.yaml",
    ];
    for (i, cfg) in configs.iter().enumerate() {
        let exe = dir.join(format!("bin dir '{i}'/snp"));
        let script = snp_cmd::scripts::render(
            std::ffi::OsStr::from_bytes(cfg),
            snp_core::stage::HookType::PrePush,
            true,
            &exe,
        );
        // Replace the fallback chain by a printer of the positional parameters and SNP_EXE.
        let s = String::from_utf8_lossy(&script).into_owned();
        let head_end = memchr::memmem::find(&script, b"# end templated\n").unwrap();
        let mut probe = script[..head_end].to_vec();
        probe.extend_from_slice(b"printf '%s\\0' \"$SNP_EXE\" \"$@\"\n");
        let p = dir.join(format!("probe{i}"));
        write_hook(&p, &probe);
        let out = output_retry(Command::new(&p).arg("orig1").arg("orig 2"));
        let parts: Vec<&[u8]> = out.stdout.split(|b| *b == 0).collect();
        assert_eq!(parts[0], exe.as_os_str().as_bytes(), "{s}");
        assert_eq!(parts[1], b"hook-impl");
        let mut want_cfg = b"--config=".to_vec();
        want_cfg.extend_from_slice(cfg);
        assert_eq!(parts[2], want_cfg.as_slice());
        assert_eq!(parts[3], b"--hook-type=pre-push");
        assert_eq!(parts[4], b"--skip-on-missing-config");
        assert_eq!(parts[5], b"--hook-dir");
        assert_eq!(parts[7], b"--");
        assert_eq!(parts[8], b"orig1");
        assert_eq!(parts[9], b"orig 2");
    }
}

