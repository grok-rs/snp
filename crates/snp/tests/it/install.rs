/// The `HERE` line of template v1 (snp 2.0.0), which v2 replaced (ADR-105).
const V1_HERE: &str = "HERE=\"$(CDPATH= cd -- \"$(dirname -- \"$0\")\" && pwd)\"";

/// The `HERE` block of template v2 (ADR-105, unreleased), which v3 replaces (ADR-135).
const V2_HERE: &str = "case $0 in */*) HERE=${0%/*} ;; *) HERE=. ;; esac\n\
                       case $HERE in *[!/]*) ;; *) HERE=/ ;; esac\n\
                       HERE=\"$(CDPATH= cd -- \"$HERE\" && pwd)\"";

/// v2's subshell line: v3 runs it, on the original `HERE`, for every shape outside its fast path.
const HERE_FALLBACK: &str = "HERE=\"$(CDPATH= cd -- \"$HERE\" && pwd)\"";

/// The `HERE` block of the rendered template (v3: parameter expansion, no subshell on the fast path).
fn here_block(script: &str) -> &str {
    let start = script.find("\ncase $0 in").unwrap() + 1;
    let end = script.find("\n\n# start templated").unwrap();
    script.get(start..end).unwrap()
}

/// A rendered pre-commit script, as text.
fn rendered_script() -> String {
    String::from_utf8(snp_cmd::scripts::render(
        std::ffi::OsStr::new(".pre-commit-config.yaml"),
        snp_core::stage::HookType::PreCommit,
        false,
        Path::new("/dne/snp"),
    ))
    .unwrap()
}

/// The rendered v3 block with every fallback counted: `HERE_FB=1` when v2's subshell line ran, `0` otherwise.
fn counted_v3_block() -> String {
    let script = rendered_script();
    let block = here_block(&script);
    assert_eq!(block.matches(HERE_FALLBACK).count(), 5, "{block}");
    let counted = block.replace(HERE_FALLBACK, &format!("{{ HERE_FB=1; {HERE_FALLBACK}; }}"));
    format!("HERE_FB=0\n{counted}")
}

/// A shell program printing v1's, v2's and v3's `HERE` and v3's fallback counter, each NUL-terminated. The three
/// blocks run in one process: each derives `HERE` from `$0` and `$PWD` alone, and their `cd`s run in subshells.
fn three_templates_program() -> String {
    format!(
        "{V1_HERE}\nprintf '%s\\0' \"$HERE\"\n{V2_HERE}\nprintf '%s\\0' \"$HERE\"\n{}\nprintf '%s\\0%s\\0' \"$HERE\" \"$HERE_FB\"\n",
        counted_v3_block()
    )
}

/// `[v1, v2, v3, fallback]` from the output of [`three_templates_program`]; `None` when a field is missing.
fn three_templates_fields(out: &[u8]) -> Option<[Vec<u8>; 4]> {
    let mut it = out.split(|b| *b == 0).map(<[u8]>::to_vec);
    let f = [it.next()?, it.next()?, it.next()?, it.next()?];
    (it.next().as_deref() == Some(&b""[..]) && it.next().is_none()).then_some(f)
}

/// A POSIX shell of the template matrices: its program, its `argv[0]` when invoked under another name, the
