/// A v1 script (snp 2.0.0) and a v2 script (ADR-105, development builds) are older snp scripts: `doctor` warns,
/// and `doctor --fix` and `install` rewrite them to v3 keeping their options (ADR-105, ADR-135). v3 keeps the v1 id
/// as its `snp 2.0 compat ID` line, so snp 2.0.x still sees an snp script, and the stable header with an unknown id
/// is never mistaken for pre-commit's script.
#[test]
fn v1_script_is_older_and_install_rewrites_it() {
    let env = tenv();
    let r = repo_with(&env, "r", LOCAL_CONFIG);
    for prior in [
        "snp-prior-5bb9bd89cf6c92c58fee7677ceaf4fc3",
        "snp-prior-405bd8559925d194c1d22af6ef66282e",
    ] {
        let old = std::fs::read_to_string(hookscripts_fixture(prior))
            .unwrap()
            .replace("--config=.pre-commit-config.yaml", "--config=my.yaml");
        write_hook(&hook(&r, "pre-commit"), old.as_bytes());
        let out = snp(&env, &r, &["doctor"]);
        let o = text(&out.stdout);
        assert!(
            o.contains(
                "warn  .git/hooks/pre-commit: an older snp hook script; `--fix` rewrites it"
            ),
            "{prior}: {o}"
        );
        let out = snp(&env, &r, &["doctor", "--fix"]);
        let o = text(&out.stdout);
        assert!(
            o.contains("ok    .git/hooks/pre-commit: runs snp"),
            "{prior}: {o}"
        );
        let script = std::fs::read_to_string(hook(&r, "pre-commit")).unwrap();
        assert!(
            script.contains("\n# ID: b5aab319837cfd7b570aecfbefd9e801\n"),
            "{script}"
        );
        assert!(script.contains("\n# snp 2.0 compat ID: 5bb9bd89cf6c92c58fee7677ceaf4fc3\n"));
        assert!(
            !script.contains("405bd8559925d194c1d22af6ef66282e"),
            "{script}"
        );
        assert!(script.contains(" --config=my.yaml "), "{script}");
        assert!(!script.contains("dirname"), "{script}");
        // `install` over an older script writes v3 too.
        write_hook(&hook(&r, "pre-commit"), old.as_bytes());
        assert_code(&snp(&env, &r, &["install", "-c", "my.yaml"]), 0);
        let again = std::fs::read_to_string(hook(&r, "pre-commit")).unwrap();
        assert!(again.contains("\n# ID: b5aab319837cfd7b570aecfbefd9e801\n"));
    }
}

