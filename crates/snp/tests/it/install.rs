/// A private copy of the snp binary at `dst`: a hard link where the filesystem allows one, else a copy made by a
/// `cp` child, so no writable fd of the copy can leak into a child forked by a concurrent test (exec of such a
/// file fails with ETXTBSY).
pub(crate) fn copy_snp(dst: &Path) {
    let src = Path::new(env!("CARGO_BIN_EXE_snp"));
    if std::fs::hard_link(src, dst).is_err() {
        copy_in_child(src, dst);
    }
}

/// Copies `src` to `dst` in a child process (Unix: `cp`), so the test process never holds a writable fd of `dst`.
fn copy_in_child(src: &Path, dst: &Path) {
    #[cfg(unix)]
    {
        let st = Command::new("cp")
            .arg("--")
            .arg(src)
            .arg(dst)
            .status()
            .unwrap();
        assert!(st.success(), "cp {} {}", src.display(), dst.display());
    }
    #[cfg(not(unix))]
    {
        std::fs::copy(src, dst).unwrap();
    }
}

/// Writes an executable hook script.
///
/// The bytes go to a non-executable sibling first and are copied into place by a child process: a write fd held
/// by this multi-threaded test process leaks into any child a concurrent test forks (until that child execs), and
/// exec of the script during that window fails with ETXTBSY.
pub(crate) fn write_hook(path: &Path, body: &[u8]) {
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    let mut staged = path.as_os_str().to_os_string();
    staged.push(".staged");
    let staged = PathBuf::from(staged);
    std::fs::write(&staged, body).unwrap();
    copy_in_child(&staged, path);
    std::fs::remove_file(&staged).unwrap();
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o755)).unwrap();
    }
}

/// `cmd.output()`, retried on ETXTBSY: a file written by another (forked, not yet exec'd) process may still be
/// open for writing for a moment.
pub(crate) fn output_retry(cmd: &mut Command) -> std::process::Output {
    let mut tries = 0;
    loop {
        match cmd.output() {
            Err(e) if e.kind() == std::io::ErrorKind::ExecutableFileBusy && tries < 100 => {
                tries += 1;
                std::thread::sleep(std::time::Duration::from_millis(10));
            }
            r => return r.unwrap(),
        }
    }
}

fn hook(r: &Path, t: &str) -> PathBuf {
    r.join(".git/hooks").join(t)
}

fn legacy(r: &Path, t: &str) -> PathBuf {
    r.join(".git/hooks").join(format!("{t}.legacy"))
}

/// `git clone <fixture> <root>/clone` (pre-commit's `cmd_output('git', 'clone', upstream, path)`).
fn clone_of(env: &TestEnv, f: Fixture) -> PathBuf {
    let upstream = env.fixture_repo(f);
    let r = env.root().join("clone");
    git(
        env,
        env.root(),
        &["clone", upstream.to_str().unwrap(), r.to_str().unwrap()],
    );
    r
}

/// `git commit -m <msg>` after touching and adding `file`: `(code, stdout + stderr)`.
fn commit_file(env: &TestEnv, r: &Path, file: &str, msg: &str) -> (i32, String) {
    std::fs::write(r.join(file), b"").unwrap();
    git(env, r, &["add", file]);
    let (code, out, err) = git(env, r, &["commit", "-m", msg]);
    (code, format!("{err}{out}"))
}

/// Runs a hook script (by its shebang) with an explicit PATH: `(code, stdout, stderr)`.
#[cfg(unix)]
fn run_script(
    env: &TestEnv,
    script: &Path,
    cwd: &Path,
    path: &str,
    extra: &[(&str, &str)],
) -> (i32, String, String) {
    let mut cmd = Command::new(script);
    env.env().apply_to(&mut cmd);
    cmd.env("PATH", path)
        .envs(extra.iter().copied())
        .current_dir(cwd);
    let out = output_retry(&mut cmd);
    (
        out.status.code().unwrap_or(-1),
        text(&out.stdout),
        text(&out.stderr),
    )
}

#[test]
fn t10_ins_01_resolve_hook_types() {
    let env = tenv();
    // explicit -t
    let r = repo_with(&env, "a", LOCAL_CONFIG);
    assert_code(&compat(&env, &r, &["install", "-t", "pre-push"]), 0);
    assert!(hook(&r, "pre-push").exists() && !hook(&r, "pre-commit").exists());
    // default: pre-commit
    let r = repo_with(&env, "b", LOCAL_CONFIG);
    assert_code(&compat(&env, &r, &["install"]), 0);
    assert!(hook(&r, "pre-commit").exists());
    // default_install_hook_types
    let r = repo_with(
        &env,
        "c",
        &format!("default_install_hook_types: [pre-push]\n{LOCAL_CONFIG}"),
    );
    assert_code(&compat(&env, &r, &["install"]), 0);
    assert!(hook(&r, "pre-push").exists() && !hook(&r, "pre-commit").exists());
    // [] installs nothing
    let r = repo_with(
        &env,
        "d",
        &format!("default_install_hook_types: []\n{LOCAL_CONFIG}"),
    );
    let out = compat(&env, &r, &["install"]);
    assert_code(&out, 0);
    assert_eq!(text(&out.stdout), "");
    // an unparsable config falls back to pre-commit
    let r = repo_with(&env, "e", "[\n");
    let out = compat(&env, &r, &["install"]);
    assert_code(&out, 0);
    assert_eq!(
        text(&out.stdout),
        "pre-commit installed at .git/hooks/pre-commit\n"
    );
}

