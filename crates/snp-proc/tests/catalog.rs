    /// `xargs.xargs` + `lang_base.run_xargs` as snp-run will compose them: `normalize_cmd` once (an `ExeError` is
    /// `(1, message)`), `partition`, the partitions on the pool with `threads = min(partitions, jobs)`, merged output
    /// concatenated in partition order, max-abs aggregation; a spawn error is `(1, python_text + "\n")` per partition.
    fn run_xargs(
        cmd: &[OsString],
        files: &[&OsStr],
        jobs: usize,
        max_len: usize,
        pty: bool,
        env: &Env,
        cwd: &Path,
    ) -> (PyStatus, Vec<u8>) {
        let cmd = match resolve::normalize_cmd(cmd, env, cwd) {
            Ok(c) => c,
            Err(e) => return (PyStatus(1), e.message().into_bytes()),
        };
        let jobs = NonZeroUsize::new(jobs).unwrap();
        let parts = xargs::partition(&cmd, files, jobs, max_len).unwrap();
        let cancel = CancelToken::new();
        let pool = JobPool::new(jobs, cancel.clone());
        let budget = budget();
        let threads = NonZeroUsize::new(parts.len().min(jobs.get())).unwrap();
        let results = pool.map_ordered(threads, parts.len(), |i| {
            let mut argv = cmd.clone();
            argv.extend(files[parts[i].clone()].iter().map(|f| f.to_os_string()));
            let spec = hook(&argv, env, cwd, &cancel);
            match spawn::merged(&spec, pty, &budget) {
                Ok(m) => Ok((m.status, bytes(&m.output))),
                Err(e) => Ok((PyStatus(1), format!("{}\n", e.python_text()).into_bytes())),
            }
        });
        let mut out = Vec::new();
        let mut codes = Vec::new();
        for r in results {
            let (st, o): (PyStatus, Vec<u8>) = r.map_err(|e: Failure| format!("{e:?}")).unwrap();
            codes.push(st);
            out.extend_from_slice(&o);
        }
        (xargs::aggregate(codes), out)
    }

