    /// `parse_shebang_test.py:125-257`.
    #[test]
    fn t10_utl_05_parse_shebang() {
        let d = tempfile::tempdir().unwrap();
        let r = d.path();
        let path_env = |extra: &[(&str, OsString)]| {
            let mut pairs: Vec<(String, OsString)> = vec![(
                "PATH".to_owned(),
                OsString::from(if cfg!(windows) { "" } else { "/usr/bin:/bin" }),
            )];
            pairs.extend(extra.iter().map(|(k, v)| ((*k).to_owned(), v.clone())));
            Env::from_pairs(pairs)
        };
        let us = probe();
        // test_file_doesnt_exist / test_find_executable_not_found_none.
        assert!(
            resolve::find_executable(OsStr::new("not-a-real-executable"), &path_env(&[]), r)
                .is_none()
        );
        // test_find_executable_full_path / test_normexe_already_full_path / test_normalize_cmd_trivial.
        assert_eq!(
            resolve::find_executable(us.as_os_str(), &path_env(&[]), r).unwrap(),
            us
        );
        assert_eq!(
            resolve::normexe(us.as_os_str(), &path_env(&[]), r).unwrap(),
            us
        );
        let trivial = vec![us.as_os_str().to_os_string(), OsString::from("hi")];
        assert_eq!(
            resolve::normalize_cmd(&trivial, &path_env(&[]), r).unwrap(),
            trivial
        );
        // test_normexe_does_not_exist(_sep), test_normexe_is_a_directory, test_normexe_not_executable.
        let msg = |s: &str| {
            resolve::normexe(OsStr::new(s), &path_env(&[]), r)
                .unwrap_err()
                .message()
        };
        assert_eq!(
            msg("i-dont-exist-lol"),
            "Executable `i-dont-exist-lol` not found"
        );
        assert_eq!(
            msg("./i-dont-exist-lol"),
            "Executable `./i-dont-exist-lol` not found"
        );
        std::fs::create_dir_all(r.join("exe")).unwrap();
        let exe = if cfg!(windows) { ".\\exe" } else { "./exe" };
        assert_eq!(msg(exe), format!("Executable `{exe}` is a directory"));
        #[cfg(unix)]
        {
            std::fs::write(r.join("plain"), b"").unwrap();
            assert_eq!(msg("./plain"), "Executable `./plain` is not executable");
            assert!(matches!(
                resolve::normexe(OsStr::new("./plain"), &path_env(&[]), r),
                Err(ExeError::NotExecutable(_))
            ));
        }
        // Shebang scripts: write_executable() of the pre-commit tests.
        let bin = r.join("bin");
        std::fs::create_dir_all(&bin).unwrap();
        let write_executable = |shebang: &str, name: &str| {
            let p = bin.join(name);
            std::fs::write(&p, format!("#!{shebang}")).unwrap();
            #[cfg(unix)]
            {
                use std::os::unix::fs::PermissionsExt;
                std::fs::set_permissions(&p, std::fs::Permissions::from_mode(0o755)).unwrap();
            }
            p
        };
        #[cfg(unix)]
        let bin_on_path = |extra: &[(&str, OsString)]| {
            let mut path = bin.clone().into_os_string();
            if cfg!(unix) {
                path.push(":/usr/bin:/bin");
            }
            let mut pairs = vec![("PATH", path)];
            pairs.extend(extra.iter().cloned());
            Env::from_pairs(pairs)
        };
        #[cfg(unix)]
        {
            let echo = resolve::find_executable(OsStr::new("echo"), &path_env(&[]), r).unwrap();
            assert!(echo.is_absolute());
            // test_normexe_gives_full_path / test_normalize_cmd_PATH.
            assert_eq!(
                resolve::normexe(OsStr::new("echo"), &path_env(&[]), r).unwrap(),
                echo
            );
            assert_eq!(
                resolve::normalize_cmd(&os(&["echo", "--version"]), &path_env(&[]), r).unwrap(),
                [echo.clone().into_os_string(), OsString::from("--version")]
            );
            // test_simple_case: `#!/usr/bin/env echo` → (echo,), then PATH lookup.
            let run = write_executable("/usr/bin/env echo", "run");
            assert_eq!(
                resolve::normalize_cmd(&[run.clone().into_os_string()], &path_env(&[]), r).unwrap(),
                [echo.clone().into_os_string(), run.clone().into_os_string()]
            );
            // test_find_executable_path_added: not found until bin/ is on PATH.
            assert!(resolve::find_executable(OsStr::new("run"), &path_env(&[]), r).is_none());
            assert_eq!(
                resolve::find_executable(OsStr::new("run"), &bin_on_path(&[]), r).unwrap(),
                run
            );
            // test_normalize_cmd_PATH_shebang_PATH.
            assert_eq!(
                resolve::normalize_cmd(&os(&["run"]), &bin_on_path(&[]), r).unwrap(),
                [echo.into_os_string(), run.clone().into_os_string()]
            );
            // test_normalize_cmd_shebang / _PATH_shebang_full_path: an absolute interpreter.
            let us_str = us.to_str().unwrap();
            std::fs::remove_file(&run).unwrap();
            let run = write_executable(us_str, "run");
            assert_eq!(
                resolve::normalize_cmd(&[run.clone().into_os_string()], &path_env(&[]), r).unwrap(),
                [us.clone().into_os_string(), run.clone().into_os_string()]
            );
            assert_eq!(
                resolve::normalize_cmd(&os(&["run"]), &bin_on_path(&[]), r).unwrap(),
                [us.into_os_string(), run.into_os_string()]
            );
        }
        // test_find_executable_path_ext: PATHEXT (any OS when the key exists), in a fresh directory.
        let _ignored: std::io::Result<()> = std::fs::remove_file(bin.join("run"));
        let myext = write_executable("/usr/bin/env sh", "run.myext");
        let sep = if cfg!(windows) { ";" } else { ":" };
        let only_path = Env::from_pairs([("PATH", bin.clone().into_os_string())]);
        assert!(resolve::find_executable(OsStr::new("run"), &only_path, r).is_none());
        assert_eq!(
            resolve::find_executable(OsStr::new("run.myext"), &only_path, r).unwrap(),
            myext
        );
        let with_ext = Env::from_pairs([
            ("PATH", bin.into_os_string()),
            ("PATHEXT", OsString::from(format!(".exe{sep}.myext"))),
        ]);
        assert_eq!(
            resolve::find_executable(OsStr::new("run"), &with_ext, r).unwrap(),
            myext
        );
    }
