    /// `util_test.py:379-401`: a missing executable is `(1, "Executable `dne` not found")`; an executable file without a
    /// shebang fails with the `OSError` text and a trailing newline (no crash, no `/bin/sh` fallback).
    #[test]
    fn t10_utl_03_cmd_output_errors() {
        let d = tempfile::tempdir().unwrap();
        let (st, out) = run_xargs(&os(&["dne"]), &[], 1, 30_000, false, &env(), d.path());
        assert_eq!(
            (st, out.as_slice()),
            (PyStatus(1), &b"Executable `dne` not found"[..])
        );
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let script = d.path().join("noshebang");
            std::fs::write(&script, b"echo hi\n").unwrap();
            std::fs::set_permissions(&script, std::fs::Permissions::from_mode(0o755)).unwrap();
            // A child forked by a concurrent test may still hold the just-written file open for a moment
            // (ETXTBSY, "Text file busy"): retry that transient error only.
            let mut attempt = 0;
            let (st, out) = loop {
                let r = run_xargs(
                    &os(&["./noshebang"]),
                    &[],
                    1,
                    30_000,
                    false,
                    &env(),
                    d.path(),
                );
                attempt += 1;
                if !r.1.starts_with(b"[Errno 26]") || attempt > 20 {
                    break r;
                }
                std::thread::sleep(Duration::from_millis(20));
            };
            assert_eq!(st, PyStatus(1));
            assert_eq!(out, b"[Errno 8] Exec format error: './noshebang'\n");
        }
    }

