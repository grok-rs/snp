    /// `xargs_test.py:16-47` on the real machine: Linux counts the affinity mask (cgroup quotas ignored, like
    /// Python), elsewhere `os.cpu_count()`. The fallback chain itself is `t10_xrg_01_cpu_count_fallbacks` in
