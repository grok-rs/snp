"""Generate `partition.tsv`: `pre_commit.xargs.partition` results of pre-commit 4.7.0 on deterministic random inputs.

Run with the oracle interpreter (never a host Python):

    target/oracle/pc470-py312/bin/python -I crates/snp-proc/tests/vectors/gen_partition.py \
        > crates/snp-proc/tests/vectors/partition.tsv

Each line: `jobs<TAB>max_len<TAB>cmd<TAB>files<TAB>result`. `cmd` is joined with U+001F; `files` is the file count
followed by the names, all U+001F-separated; `result` is the comma-separated partition sizes or `ERR:<argument>`
(`ArgumentTooLongError`). Lengths are POSIX (UTF-8 bytes); the replaying test is `#[cfg(unix)]`.
"""
from __future__ import annotations

import random
import sys

from pre_commit import xargs

SEP = '\x1f'
ALPHABET = 'abcdefghijklmnopqrstuvwxyz0123456789._-/ é😑'


def word(rng: random.Random, lo: int, hi: int) -> str:
    return ''.join(rng.choice(ALPHABET) for _ in range(rng.randint(lo, hi)))


def main() -> int:
    rng = random.Random(20261008)
    out = sys.stdout
    out.write('# pre_commit.xargs.partition (pre-commit 4.7.0, CPython 3.12) — generated by gen_partition.py\n')
    for _ in range(400):
        cmd = tuple(word(rng, 1, 8) for _ in range(rng.randint(1, 4)))
        files = tuple(word(rng, 0, 40) for _ in range(rng.randint(0, 150)))
        jobs = rng.randint(1, 40)
        max_len = rng.choice((rng.randint(10, 100), rng.randint(100, 2000), 131072))
        try:
            parts = xargs.partition(cmd, files, jobs, max_len)
        except xargs.ArgumentTooLongError as e:
            result = 'ERR:' + e.args[0]
        else:
            result = ','.join(str(len(p) - len(cmd)) for p in parts)
        out.write(f'{jobs}\t{max_len}\t{SEP.join(cmd)}\t{len(files)}{SEP}{SEP.join(files)}\t{result}\n')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
