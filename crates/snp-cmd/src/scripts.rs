/// The script before the templated block (11 §A.6, ARCHITECTURE §9.7): the three identity lines are load-bearing
/// (pre-commit's and prek's `is_our_script` search them anywhere in the file).
const HEAD: &str = "#!/bin/sh
# File generated by snp: https://github.com/grok-rs/snp
# ID: 5bb9bd89cf6c92c58fee7677ceaf4fc3
# pre-commit compat ID: 138fd403232d2ddd5efb44317e38bf03
# prek compat ID: 182c10f181da4464a3eec51b83331688

HERE=\"$(CDPATH= cd -- \"$(dirname -- \"$0\")\" && pwd)\"

# start templated
";

/// The fallback chain after the templated block, up to the kill-switch `shift` (ADR-048, ADR-038).
const TAIL_HEAD: &str = "# end templated

if [ -n \"${SNP_BIN:-}\" ] && [ -x \"$SNP_BIN\" ]; then
    exec \"$SNP_BIN\" \"$@\"
elif [ -x \"$SNP_EXE\" ]; then
    exec \"$SNP_EXE\" \"$@\"
elif command -v snp > /dev/null 2>&1; then
    exec snp \"$@\"
elif command -v pre-commit > /dev/null 2>&1; then
    exec pre-commit \"$@\"
fi
case \"${SNP:-}\" in
    0|false)
        # kill switch with no snp binary: still run the chained legacy hook (git-lfs), never fail the commit
";

/// The rest of the kill-switch branch and the fail-closed exit (M5).
const TAIL_END: &str = "        if [ -x \"$HERE/$SNP_HOOK_TYPE.legacy\" ]; then exec \"$HERE/$SNP_HOOK_TYPE.legacy\" \"$@\"; fi
        exit 0;;
esac
echo '`snp` not found.  Did you forget to activate your virtualenv?' 1>&2
exit 1
";

/// The executable name a hook embeds for `brand`: `snp[.exe]` or `pre-commit[.exe]` (ADR-060).
fn brand_exe_name(brand: Brand) -> String {
    format!("{}{}", brand.prog(), std::env::consts::EXE_SUFFIX)
}

/// Whether `s` contains a path separator (`/`; also `\` on Windows).
fn has_separator(s: &OsStr) -> bool {
    let b = s.as_encoded_bytes();
    b.contains(&b'/') || (cfg!(windows) && b.contains(&b'\\'))
}

fn is_file(p: &Path) -> bool {
    fs::metadata(p).is_ok_and(|m| m.is_file())
}

/// 11 §A.19.3: the stable executable to embed as `SNP_EXE`, never canonicalised. Candidates in order:
/// `absolute(arg0)` when arg0 contains a separator and the result has no `..` component (`../../bin/snp` run from
/// the repository would tie the hook to the repository's own path; `..` is never folded lexically, which is wrong
/// across symlinked directories); then each absolute PATH entry joined with the brand's name —
/// `snp[.exe]` (snp brand) or `pre-commit[.exe]` (compat brand, so hooks keep the compat brand, ADR-060); then
/// `current`. The first candidate that is a file and `same_file` as `current` wins (Unix (dev, ino); Windows volume
/// serial + file index).
///
/// pre-commit embeds `sys.executable` (`install_uninstall.py:105`), whose Linux value is never resolved through
/// symlinks; snp's `current_exe()` is (`/proc/self/exe`), so a versioned real path (Homebrew Cellar, mise, cargo-binstall)
/// would vanish on the next upgrade — hence the preference for the path the user actually invoked.
pub fn select_exe(brand: Brand, arg0: Option<&OsStr>, env: &Env, current: &Path) -> PathBuf {
    let mut cands: Vec<PathBuf> = Vec::new();
    if let Some(a) = arg0.filter(|a| has_separator(a))
        && let Ok(abs) = std::path::absolute(a)
        && !abs
            .components()
            .any(|c| matches!(c, std::path::Component::ParentDir))
    {
        cands.push(abs);
    }
    if let Some(path) = env.get("PATH") {
        let name = brand_exe_name(brand);
        for dir in std::env::split_paths(path) {
            if !dir.as_os_str().is_empty() && dir.is_absolute() {
                cands.push(dir.join(&name));
            }
        }
    }
    cands
        .into_iter()
        .find(|c| is_file(c) && snp_os::same_file(c, current).unwrap_or(false))
        .unwrap_or_else(|| without_dot_dot(current))
}

/// `current` itself, or its canonical path when it holds a `..`: macOS's `current_exe()` is the invoked path made
/// absolute (`<repo>/../pbin/snp`), not the kernel's resolved one as on Linux, and a `..` must never be embedded.
fn without_dot_dot(current: &Path) -> PathBuf {
    let dotted = current
        .components()
        .any(|c| matches!(c, std::path::Component::ParentDir));
    if dotted {
        snp_os::realpath::realpath_nonstrict(current, Path::new("/"))
            .unwrap_or_else(|_| current.to_path_buf())
    } else {
        current.to_path_buf()
    }
}

/// BLAKE3 of a file's bytes, streamed.
fn file_hash(p: &Path) -> io::Result<blake3::Hash> {
    let mut f = fs::File::open(p)?;
    let mut h = blake3::Hasher::new();
    let mut buf = vec![0_u8; 64 << 10];
    loop {
        let n = f.read(&mut buf)?;
        if n == 0 {
            return Ok(h.finalize());
        }
        h.update(buf.get(..n).unwrap_or_default());
    }
}

/// `^pre-commit [0-9.]+ \(snp ([^)]+)\)$` over one `--version` line (11 §A.19.4); the snp version on a match.
pub(crate) fn snp_version_of(line: &str) -> Option<&str> {
    let rest = line.strip_prefix("pre-commit ")?;
    let (num, rest) = rest.split_once(' ')?;
    if num.is_empty() || !num.bytes().all(|b| b.is_ascii_digit() || b == b'.') {
        return None;
    }
    let v = rest.strip_prefix("(snp ")?.strip_suffix(')')?;
    (!v.is_empty() && !v.contains(')')).then_some(v)
}

/// Runs `exe --version` with stdin `/dev/null`, a 10 s deadline (killed after it) and the inherited environment
/// plus `SNP_VERSION_PROBE=1` (11 §A.19.8: the probe mirrors what a hook would see); the first stdout line, `None`
/// on any failure. With the variable an snp of any brand prints `pre-commit 4.6.2 (snp X)` (§A.19.4), which a plain
/// compat-brand `--version` (`pre-commit 4.6.2`, ADR-023) would not reveal; Python pre-commit ignores it.
pub(crate) fn version_probe(exe: &Path) -> Option<String> {
    let env = Env::capture_process().patched(&EnvPatch::default().set("SNP_VERSION_PROBE", "1"));
    let out = probe_output_env(exe, &[OsStr::new("--version")], None, &env, PROBE_DEADLINE)?;
    let text = String::from_utf8_lossy(&out.1);
    snp_pycompat::text::splitlines(&text)
        .next()
        .map(|l| l.trim_end().to_owned())
}

/// How long a probe may run before its process group is terminated.
const PROBE_DEADLINE: Duration = Duration::from_secs(10);

/// `argv[0] args…` with stdin `/dev/null`, stdout captured, stderr discarded, a 10 s deadline: `(status, stdout)`
/// (`status` is `None` for a death by signal). `None` on a spawn failure or when the deadline expired.
///
/// Spawned through `snp_proc::spawn::capture` in its own process group (`Group::Isolated`, `Role::Tool`): at the
/// deadline the whole group gets SIGTERM, then SIGKILL after `SNP_KILL_GRACE`, and the wait ends after the drain
/// even when a grandchild still holds the stdout pipe (Windows: the Job Object equivalent).
pub(crate) fn probe_output(
    exe: &Path,
    args: &[&OsStr],
    cwd: Option<&Path>,
) -> Option<(Option<i32>, Vec<u8>)> {
    probe_output_env(exe, args, cwd, &Env::capture_process(), PROBE_DEADLINE)
}

fn probe_output_env(
    exe: &Path,
    args: &[&OsStr],
    cwd: Option<&Path>,
    env: &Env,
    limit: Duration,
) -> Option<(Option<i32>, Vec<u8>)> {
    let argv: Vec<OsString> = std::iter::once(exe.as_os_str())
        .chain(args.iter().copied())
        .map(OsStr::to_os_string)
        .collect();
    let cancel = CancelToken::new();
    let deadline = Instant::now().checked_add(limit);
    let spec = Spec {
        argv: &argv,
        env,
        cwd: cwd.unwrap_or_else(|| Path::new(".")),
        stdin: Stdin::Null,
        group: Group::Isolated,
        role: Role::Tool,
        deadline,
        cancel: &cancel,
    };
    let out = snp_proc::spawn::capture(&spec).ok()?;
    if deadline.is_none_or(|d| Instant::now() >= d) {
        return None;
    }
    let code = i32::try_from(out.status.0).ok().filter(|c| *c >= 0);
    let mut stdout = out.stdout;
    stdout.truncate(1 << 20);
    Some((code, stdout))
}

/// 11 §A.19.4: same file, or a copy with equal length and BLAKE3, or `--version` matching `pre-commit X (snp Y)`.
///
/// Decides whether an existing `SNP_EXE` or `pre-commit` alias still points at this snp (`doctor`, `self alias`).
pub fn is_snp(file: &Path, current: &Path) -> bool {
    if snp_os::same_file(file, current).unwrap_or(false) {
        return true;
    }
    let (Ok(a), Ok(b)) = (fs::metadata(file), fs::metadata(current)) else {
        return false;
    };
    if !a.is_file() {
        return false;
    }
    if a.len() == b.len()
        && let (Ok(x), Ok(y)) = (file_hash(file), file_hash(current))
        && x == y
    {
        return true;
    }
    version_probe(file).is_some_and(|l| snp_version_of(&l).is_some())
}

/// `SNP_EXE` as the script spells it: shlex-quoted bytes on Unix; on Windows with forward slashes (11 §A.6).
fn exe_word(snp_exe: &Path) -> Vec<u8> {
    let raw = snp_exe.as_os_str().as_encoded_bytes();
    if cfg!(windows) {
        let fwd: Vec<u8> = raw
            .iter()
            .map(|&b| if b == b'\\' { b'/' } else { b })
            .collect();
        quote_bytes(&fwd).into_owned()
    } else {
        quote_bytes(raw).into_owned()
    }
}

/// The templated `hook-impl` tokens before git's own arguments, unquoted: pre-commit's `ARGS` order
/// (`install_uninstall.py:88-90`) plus the fixed `--hook-dir "$HERE" --` tail of its template.
fn templated_args(cfg: &OsStr, t: HookType, skip_missing: bool) -> Vec<Vec<u8>> {
    let mut config = b"--config=".to_vec();
    config.extend_from_slice(cfg.as_encoded_bytes());
    let mut v = vec![
        b"hook-impl".to_vec(),
        config,
        format!("--hook-type={}", t.as_str()).into_bytes(),
    ];
    if skip_missing {
        v.push(b"--skip-on-missing-config".to_vec());
    }
    v
}

/// The §9.7 template, LF.
///
/// The templated `set --` line is `hook-impl`, `--config=<cfg>`, `--hook-type=<T>`, optional
/// `--skip-on-missing-config`, then `--hook-dir "$HERE" -- "$@"` — exactly pre-commit's `ARGS` (so the
/// `pre-commit` fallback accepts it); every token and `SNP_EXE` go through `shlex.quote` (bytes on Unix); the
/// kill-switch `shift` count equals the number of templated tokens before git's arguments.
pub fn render(cfg: &OsStr, t: HookType, skip_missing: bool, snp_exe: &Path) -> Vec<u8> {
    let args = templated_args(cfg, t, skip_missing);
    let mut out = HEAD.as_bytes().to_vec();
    out.extend_from_slice(b"SNP_EXE=");
    out.extend_from_slice(&exe_word(snp_exe));
    out.extend_from_slice(b"\nSNP_HOOK_TYPE=");
    out.extend_from_slice(&quote_bytes(t.as_str().as_bytes()));
    out.extend_from_slice(b"\nset --");
    for a in &args {
        out.push(b' ');
        out.extend_from_slice(&quote_bytes(a));
    }
    out.extend_from_slice(b" --hook-dir \"$HERE\" -- \"$@\"\n");
    out.extend_from_slice(TAIL_HEAD.as_bytes());
    // hook-impl … + `--hook-dir` + `"$HERE"` + `--`
    let shift = args.len().saturating_add(3);
    out.extend_from_slice(format!("        shift {shift}\n").as_bytes());
    out.extend_from_slice(TAIL_END.as_bytes());
    out
}

/// The command of a git ≥ 2.54 config hook (`hook.snp-<type>.command`, ARCHITECTURE §9.7): the shlex-quoted
/// `select_exe` path, the same `hook-impl` tokens as [`render`] without `--hook-dir`, and a trailing ` --` (git
/// appends `"$@"`; 02 G.5).
pub(crate) fn config_hook_command(
    cfg: &OsStr,
    t: HookType,
    skip_missing: bool,
    snp_exe: &Path,
) -> Vec<u8> {
    let mut out = exe_word(snp_exe);
    for a in templated_args(cfg, t, skip_missing) {
        out.push(b' ');
        out.extend_from_slice(&quote_bytes(&a));
    }
    out.extend_from_slice(b" --");
    out
}

/// M1/M1b/M2/M3/M12 of 11 §A.5.4 — written to **stderr** in both brands (D-DIAG-02).
///
/// The templates in order: M1 (`Replaced hook script from {owner} at {hook_path}`), M1's ` (Python: {python})` and
/// ` (could not read its options; defaults used)` suffixes, M1b, M2, M3 and M12, with `{prog}` already
/// substituted for `brand`; the other `{…}` placeholders are filled by the caller.
pub fn migration_notes(brand: Brand) -> &'static [&'static str] {
    crate::messages::migration_notes(brand)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn version_line_shape() {
        assert_eq!(
            snp_version_of("pre-commit 4.6.2 (snp 2.0.0)"),
            Some("2.0.0")
        );
        assert_eq!(snp_version_of("pre-commit 4.6.2"), None);
        assert_eq!(snp_version_of("pre-commit 4.6.2 (snp )"), None);
        assert_eq!(snp_version_of("pre-commit x (snp 1)"), None);
        assert_eq!(snp_version_of("pre-commit 4.6.2 (snp 1) x"), None);
        assert_eq!(snp_version_of("snp 2.0.0"), None);
    }

    #[test]
    fn notes_are_the_seven_templates() {
        for b in [Brand::PreCommit, Brand::Snp] {
            let n = migration_notes(b);
            assert_eq!(n.len(), 7);
            assert!(n.first().unwrap().starts_with("Replaced hook script from"));
        }
    }

    #[test]
    fn config_hook_command_ends_with_double_dash() {
        let c = config_hook_command(
            OsStr::new(".pre-commit-config.yaml"),
            HookType::PrePush,
            true,
            Path::new("/usr/bin/snp"),
        );
        assert_eq!(
            String::from_utf8(c).unwrap(),
            "/usr/bin/snp hook-impl --config=.pre-commit-config.yaml --hook-type=pre-push \
             --skip-on-missing-config --"
        );
    }

    #[cfg(unix)]
    #[test]
    fn select_exe_skips_a_dotted_arg0() {
        let d = tempfile::tempdir().unwrap();
        let bin = d.path().join("bin");
        let repo = d.path().join("w/repo");
        fs::create_dir_all(&bin).unwrap();
        fs::create_dir_all(&repo).unwrap();
        let exe = bin.join("snp");
        fs::write(&exe, b"x").unwrap();
        let rel = Path::new("../../bin/snp");
        let env = Env::from_pairs([("PATH", bin.as_os_str())]);
        // `absolute` resolves against the process cwd; use an absolute dotted arg0 to stay cwd-independent.
        let dotted = repo.join(rel);
        assert_eq!(
            select_exe(Brand::Snp, Some(dotted.as_os_str()), &env, &exe),
            exe
        );
        let none = Env::from_pairs::<&str, &str>([]);
        assert_eq!(
            select_exe(Brand::Snp, Some(dotted.as_os_str()), &none, &exe),
            exe
        );
        assert_eq!(
            select_exe(Brand::Snp, Some(exe.as_os_str()), &none, &exe),
            exe
        );
        // macOS: `current_exe()` itself may be the dotted invocation path; the fallback is then its canonical path.
        let canonical = snp_os::realpath::realpath_nonstrict(&exe, Path::new("/")).unwrap();
        assert_eq!(
            select_exe(Brand::Snp, Some(dotted.as_os_str()), &none, &dotted),
            canonical
        );
    }

    /// A config path holding newlines (`snp install -c $'my\ncfg.yaml'`) reads back from the rendered script.
    #[cfg(unix)]
    #[test]
    fn multi_line_tokens_parse_back() {
        for cfg in ["my\ncfg.yaml", "a\r\nb", "x\n", "\n#y"] {
            let script = render(
                OsStr::new(cfg),
                HookType::PreCommit,
                false,
                Path::new("/u/b\nin/snp"),
            );
            let p = parse_script_args(&Owner::Snp { stale: false }, &script).unwrap();
            assert_eq!(p.config.as_deref(), Some(cfg.as_bytes()));
            assert_eq!(p.snp_exe.as_deref(), Some(&b"/u/b\nin/snp"[..]));
        }
    }

    /// A grandchild holding the stdout pipe cannot extend the probe past its deadline: the whole group is killed.
    #[cfg(unix)]
    #[test]
    fn probe_deadline_kills_the_group() {
        let t = Instant::now();
        let r = probe_output_env(
            Path::new("/bin/sh"),
            &[
                OsStr::new("-c"),
                OsStr::new("sleep 30 & sleep 30; echo late"),
            ],
            None,
            &Env::capture_process(),
            Duration::from_millis(300),
        );
        assert_eq!(r, None);
        assert!(t.elapsed() < Duration::from_secs(8), "{:?}", t.elapsed());
        let ok = probe_output(
            Path::new("/bin/sh"),
            &[OsStr::new("-c"), OsStr::new("echo hi; exit 3")],
            None,
        );
        assert_eq!(ok, Some((Some(3), b"hi\n".to_vec())));
    }

    #[cfg(unix)]
    mod roundtrip {
        use std::os::unix::ffi::OsStrExt;

        use proptest::prelude::*;

        use super::*;

        proptest! {
            /// Every embedded token of a rendered script reads back unchanged through the snp-script parser
            /// (`doctor --fix` keeps an snp script's options).
            #[test]
            fn rendered_tokens_parse_back(
                cfg in proptest::collection::vec(any::<u8>().prop_filter("no NUL", |b| *b != 0), 1..64),
                exe in proptest::collection::vec(any::<u8>().prop_filter("no NUL", |b| *b != 0), 1..64),
                skip in any::<bool>(),
            ) {
                let script = render(OsStr::from_bytes(&cfg), HookType::CommitMsg, skip, Path::new(OsStr::from_bytes(&exe)));
                let parsed = parse_script_args(&Owner::Snp { stale: false }, &script).unwrap();
                prop_assert_eq!(parsed.config.as_deref(), Some(cfg.as_slice()));
                prop_assert_eq!(parsed.snp_exe.as_deref(), Some(exe.as_slice()));
                prop_assert_eq!(parsed.skip_on_missing_config, skip);
            }
        }
    }
}
