//! Behaviour of `snp_migrate::lefthook` through the public API: config lookup and formats (05 §2.1–§2.2), errors
//! (exit 1), `--strict` (exit 2 on every lossy feature of 05 §19), local-only mode and the report format (§19.10).
//!
//! Owner: WP-34.

#[cfg(test)]
mod conversion {
    use std::path::Path;

    use snp_core::failure::Failure;
    use snp_migrate::{Converted, LefthookOpts};

    fn opts(root: &Path) -> LefthookOpts {
        LefthookOpts {
            root: root.to_path_buf(),
            config: None,
            output: None,
            portable: false,
            local: false,
            strict: false,
        }
    }

    fn tree(files: &[(&str, &str)]) -> tempfile::TempDir {
        let d = tempfile::tempdir().unwrap();
        for (p, text) in files {
            let path = d.path().join(p);
            std::fs::create_dir_all(path.parent().unwrap()).unwrap();
            std::fs::write(path, text).unwrap();
        }
        d
    }

    fn convert(files: &[(&str, &str)]) -> Converted {
        let d = tree(files);
        snp_migrate::lefthook(&opts(d.path())).unwrap()
    }

    fn stderr(f: &Failure) -> (i32, String) {
        match f {
            Failure::SystemExit { code, stderr } => {
                (*code, String::from_utf8(stderr.clone()).unwrap())
            }
            other => panic!("{other:?}"),
        }
    }

    fn body(c: &Converted) -> String {
        c.config_yaml.lines().skip(1).collect::<Vec<_>>().join("\n")
    }

    const WORKED_YAML: &str = "pre-commit:\n  parallel: true\n  jobs:\n    - name: eslint\n      glob: \"*.{js,ts}\"\n      run: yarn eslint --fix {staged_files}\n      stage_fixed: true\npre-push:\n  commands:\n    test:\n      run: yarn test\n      timeout: 5m\n";

    #[test]
    fn json_jsonc_and_toml_read_like_yaml() {
        let yaml = convert(&[("lefthook.yml", WORKED_YAML)]);
        let json = r#"{"pre-commit": {"parallel": true, "jobs": [{"name": "eslint", "glob": "*.{js,ts}", "run": "yarn eslint --fix {staged_files}", "stage_fixed": true}]}, "pre-push": {"commands": {"test": {"run": "yarn test", "timeout": "5m"}}}}"#;
        let jsonc = "{\n  // comment\n  \"pre-commit\": {\"parallel\": true, /* inline */ \"jobs\": [{\"name\": \"eslint\", \"glob\": \"*.{js,ts}\", \"run\": \"yarn eslint --fix {staged_files}\", \"stage_fixed\": true,},],},\n  \"pre-push\": {\"commands\": {\"test\": {\"run\": \"yarn test\", \"timeout\": \"5m\"}}},\n}\n";
        let toml = "[pre-commit]\nparallel = true\n[[pre-commit.jobs]]\nname = \"eslint\"\nglob = \"*.{js,ts}\"\nrun = \"yarn eslint --fix {staged_files}\"\nstage_fixed = true\n[pre-push.commands.test]\nrun = \"yarn test\"\ntimeout = \"5m\"\n";
        for (name, text) in [
            ("lefthook.json", json),
            ("lefthook.jsonc", jsonc),
            ("lefthook.toml", toml),
        ] {
            let c = convert(&[(name, text)]);
            assert_eq!(body(&c), body(&yaml), "{name}");
            assert!(c.config_yaml.starts_with(&format!(
                "# Generated by `snp migrate lefthook` from {name}\n"
            )));
        }
    }

    #[test]
    fn lookup_is_extension_major() {
        let one = "pre-commit:\n  commands:\n    a:\n      run: echo one\n";
        let two = "pre-commit:\n  commands:\n    a:\n      run: echo two\n";
        // `.lefthook.yml` (a .yml name) beats `lefthook.yaml`; `lefthook.yml` beats `.lefthook.yml`.
        let c = convert(&[(".lefthook.yml", one), ("lefthook.yaml", two)]);
        assert!(c.config_yaml.contains("entry: echo one"));
        let c = convert(&[(".lefthook.yml", two), ("lefthook.yml", one)]);
        assert!(c.config_yaml.contains("entry: echo one"));
        let c = convert(&[(
            ".config/lefthook.toml",
            "[pre-commit.commands.a]\nrun = 'echo three'\n",
        )]);
        assert!(c.config_yaml.contains("entry: echo three"));
    }

    #[test]
    fn explicit_config_and_yaml12_booleans() {
        let d = tree(&[(
            "ci/hooks.yml",
            "pre-commit:\n  parallel: yes\n  commands:\n    a: {run: echo a}\n    b: {run: echo b}\n",
        )]);
        let mut o = opts(d.path());
        o.config = Some("ci/hooks.yml".into());
        // `yes` is a string under YAML 1.2; mapstructure's ParseBool rejects it.
        let e = snp_migrate::lefthook(&o).unwrap_err();
        let (code, text) = stderr(&e);
        assert_eq!(code, 1);
        assert_eq!(
            text,
            "snp migrate lefthook: pre-commit.parallel: expected a bool, got the string \"yes\"\n"
        );
        std::fs::write(d.path().join("ci/hooks.yml"), "pre-commit:\n  parallel: 'true'\n  commands:\n    a: {run: echo a}\n    b: {run: echo b}\n").unwrap();
        let c = snp_migrate::lefthook(&o).unwrap();
        assert!(c.config_yaml.contains("priority: 0"));
        assert!(c.config_yaml.contains("from ci/hooks.yml"));
    }

    #[test]
    fn errors_exit_1() {
        let d = tree(&[]);
        let (code, text) = stderr(&snp_migrate::lefthook(&opts(d.path())).unwrap_err());
        assert_eq!(code, 1);
        assert!(
            text.starts_with("snp migrate lefthook: No config files with names [\"lefthook\" \".lefthook\" \".config/lefthook\"] have been found in \""),
            "{text}"
        );
        let mut o = opts(d.path());
        o.config = Some("nope.yml".into());
        let (code, text) = stderr(&snp_migrate::lefthook(&o).unwrap_err());
        assert_eq!(code, 1);
        assert!(text.contains("not found!"), "{text}");
        let d = tree(&[("lefthook.yml", "pre-commit: [\n")]);
        let (code, text) = stderr(&snp_migrate::lefthook(&opts(d.path())).unwrap_err());
        assert_eq!(code, 1);
        assert!(
            text.starts_with("snp migrate lefthook: lefthook.yml: "),
            "{text}"
        );
        let d = tree(&[
            ("lefthook.yml", "extends: [base.conf]\n"),
            ("base.conf", "x: 1\n"),
        ]);
        let (_, text) = stderr(&snp_migrate::lefthook(&opts(d.path())).unwrap_err());
        assert_eq!(
            text,
            "snp migrate lefthook: can't parse config 'base.conf', file has unsupported or no extension\nhint: rename base.conf to base.conf.yml\n"
        );
        let d = tree(&[("lefthook.yml", "- a\n")]);
        let (_, text) = stderr(&snp_migrate::lefthook(&opts(d.path())).unwrap_err());
        assert!(
            text.contains("expected a mapping at the top level, got a list"),
            "{text}"
        );
        let d = tree(&[(
            "lefthook-local.yml",
            "pre-commit:\n  commands:\n    a: {run: x}\n",
        )]);
        let (_, text) = stderr(&snp_migrate::lefthook(&opts(d.path())).unwrap_err());
        assert!(text.contains("convert it with --local"), "{text}");
    }

    #[test]
    fn extends_glob_and_recursion_warning() {
        let c = convert(&[
            (
                "lefthook.yml",
                "extends: ['conf/*.yml', conf/a.yml]\npre-commit:\n  commands:\n    a: {run: echo main}\n",
            ),
            (
                "conf/a.yml",
                "pre-commit:\n  commands:\n    a: {run: echo a}\n",
            ),
            (
                "conf/b.yml",
                "pre-commit:\n  commands:\n    b: {run: echo b}\n",
            ),
        ]);
        assert!(
            c.config_yaml.contains("entry: echo a\n"),
            "{}",
            c.config_yaml
        );
        assert!(c.config_yaml.contains("entry: echo b\n"));
        assert!(
            c.report.iter().any(|l| l == "snp-migrate: warning: lefthook.yml: possible recursion in extends: path conf/a.yml is specified multiple times; skipped"),
            "{:?}",
            c.report
        );
    }

    #[test]
    fn local_only_mode_goes_into_the_overlay() {
        let d = tree(&[(
            "lefthook-local.yml",
            "pre-commit:\n  commands:\n    mine: {run: echo mine}\n",
        )]);
        let mut o = opts(d.path());
        o.local = true;
        let c = snp_migrate::lefthook(&o).unwrap();
        assert!(c.config_yaml.ends_with("repos: []\n"), "{}", c.config_yaml);
        let overlay = c.overlay_yaml.unwrap();
        assert!(overlay.contains("\nhooks: {}\n"), "{overlay}");
        assert!(
            overlay.contains("\nrepos:\n  - repo: local\n    hooks:\n      - id: mine\n"),
            "{overlay}"
        );
    }

    #[test]
    fn overlay_uses_entry_placeholder() {
        let d = tree(&[
            (
                "lefthook.yml",
                "pre-commit:\n  commands:\n    test:\n      run: yarn test {staged_files}\n      env: {A: '1'}\n",
            ),
            (
                "lefthook-local.yml",
                "pre-commit:\n  commands:\n    test:\n      run: docker compose run app {cmd}\n      env: {B: '2'}\n",
            ),
        ]);
        let mut o = opts(d.path());
        o.local = true;
        let c = snp_migrate::lefthook(&o).unwrap();
        assert_eq!(
            c.overlay_yaml.unwrap(),
            "# Generated by `snp migrate lefthook --local` from lefthook-local.yml\n# Personal overrides for snp (never read by pre-commit); add this file to .gitignore.\nhooks:\n  test:\n    entry: docker compose run app {entry}\n    env: {B: '2'}\n"
        );
        assert!(!c.lossy);
    }

    #[test]
    fn report_summary_line() {
        let c = convert(&[("lefthook.yml", WORKED_YAML)]);
        assert_eq!(
            c.report,
            [
                "Converted 2 jobs from 2 lefthook hooks into 2 hooks (0 warnings, 0 lossy conversions)."
            ]
        );
        assert!(!c.lossy);
    }

    /// Every lossy feature of 05 §19, each alone in a config: `--strict` exits 2 (nothing converted), without it the
    /// conversion succeeds and reports `lossy: true`.
    #[test]
    #[expect(
        clippy::literal_string_with_formatting_args,
        reason = "lefthook `{files}` templates, not format arguments"
    )]
    fn strict_exits_2_on_every_lossy_feature() {
        /// `(feature, files, portable)`.
        type Case<'a> = (&'a str, &'a [(&'a str, &'a str)], bool);
        let cases: &[Case<'_>] = &[
            (
                "remotes",
                &[(
                    "lefthook.yml",
                    "remotes:\n  - git_url: https://example.invalid/x\npre-commit:\n  commands:\n    a: {run: x}\n",
                )],
                false,
            ),
            (
                "setup",
                &[(
                    "lefthook.yml",
                    "pre-commit:\n  setup:\n    - run: npm ci\n  commands:\n    a: {run: x}\n",
                )],
                false,
            ),
            (
                "non-pre-commit git hook",
                &[(
                    "lefthook.yml",
                    "pre-receive:\n  commands:\n    a: {run: x}\n",
                )],
                false,
            ),
            (
                "positional without equivalent",
                &[(
                    "lefthook.yml",
                    "pre-commit:\n  commands:\n    a: {run: 'echo {1}'}\n",
                )],
                false,
            ),
            (
                "piped group",
                &[(
                    "lefthook.yml",
                    "pre-commit:\n  jobs:\n    - group:\n        piped: true\n        jobs: [{run: a}, {run: b}]\n",
                )],
                false,
            ),
            (
                "portable interactive",
                &[(
                    "lefthook.yml",
                    "pre-commit:\n  commands:\n    a: {run: x, interactive: true}\n",
                )],
                true,
            ),
            (
                "unknown MIME type",
                &[(
                    "lefthook.yml",
                    "pre-commit:\n  commands:\n    a: {run: x, file_types: [text/x-cobol]}\n",
                )],
                false,
            ),
            (
                "timeout over 24h",
                &[(
                    "lefthook.yml",
                    "pre-commit:\n  commands:\n    a: {run: x, timeout: 25h}\n",
                )],
                false,
            ),
            (
                "invalid timeout",
                &[(
                    "lefthook.yml",
                    "pre-commit:\n  commands:\n    a: {run: x, timeout: soon}\n",
                )],
                false,
            ),
            (
                "env name",
                &[(
                    "lefthook.yml",
                    "pre-commit:\n  commands:\n    a: {run: x, env: {'A=B': c}}\n",
                )],
                false,
            ),
            (
                "absolute root",
                &[(
                    "lefthook.yml",
                    "pre-commit:\n  commands:\n    a: {run: x, root: /etc}\n",
                )],
                false,
            ),
            (
                "invalid ref glob",
                &[(
                    "lefthook.yml",
                    "pre-commit:\n  commands:\n    a: {run: x, skip: [{ref: 'a[b'}]}\n",
                )],
                false,
            ),
            (
                "uncombinable only",
                &[(
                    "lefthook.yml",
                    "pre-commit:\n  only: [merge]\n  commands:\n    a: {run: x, only: [rebase]}\n",
                )],
                false,
            ),
            (
                "piped and parallel",
                &[(
                    "lefthook.yml",
                    "pre-commit:\n  piped: true\n  parallel: true\n  commands:\n    a: {run: x}\n",
                )],
                false,
            ),
            (
                "fail_on_changes value",
                &[(
                    "lefthook.yml",
                    "pre-commit:\n  fail_on_changes: sometimes\n  commands:\n    a: {run: x}\n",
                )],
                false,
            ),
            (
                "two file templates",
                &[(
                    "lefthook.yml",
                    "pre-commit:\n  commands:\n    a: {run: 'x {all_files} {files}', files: git ls-files}\n",
                )],
                false,
            ),
            (
                "push files outside pre-push",
                &[(
                    "lefthook.yml",
                    "pre-commit:\n  commands:\n    a: {run: 'x {push_files}'}\n",
                )],
                false,
            ),
            (
                "file_types on a shell list",
                &[(
                    "lefthook.yml",
                    "pre-commit:\n  commands:\n    a: {run: 'x {all_files}', file_types: [text]}\n",
                )],
                false,
            ),
            (
                "script copies",
                &[
                    (
                        "lefthook.yml",
                        "pre-commit:\n  scripts:\n    a.sh: {runner: sh}\n",
                    ),
                    (".lefthook/pre-commit/a.sh", "true\n"),
                    (".config/lefthook/pre-commit/a.sh", "true\n"),
                ],
                false,
            ),
            (
                "portable skip",
                &[(
                    "lefthook.yml",
                    "pre-commit:\n  commands:\n    a: {run: x, skip: [merge]}\n",
                )],
                true,
            ),
            (
                "portable stage_fixed",
                &[(
                    "lefthook.yml",
                    "pre-commit:\n  commands:\n    a: {run: x, stage_fixed: true}\n",
                )],
                true,
            ),
            (
                "portable timeout",
                &[(
                    "lefthook.yml",
                    "pre-commit:\n  commands:\n    a: {run: x, timeout: 1m}\n",
                )],
                true,
            ),
            (
                "portable use_stdin",
                &[(
                    "lefthook.yml",
                    "pre-push:\n  commands:\n    a: {run: x, use_stdin: true}\n",
                )],
                true,
            ),
        ];
        for (what, files, portable) in cases {
            let d = tree(files);
            let mut o = opts(d.path());
            o.portable = *portable;
            let c = snp_migrate::lefthook(&o).unwrap_or_else(|e| panic!("{what}: {e:?}"));
            assert!(c.lossy, "{what}: {:?}", c.report);
            o.strict = true;
            let (code, text) = stderr(&snp_migrate::lefthook(&o).unwrap_err());
            assert_eq!(code, 2, "{what}");
            assert!(text.contains(": lossy: "), "{what}: {text}");
            assert!(
                text.ends_with(
                    "snp migrate lefthook: --strict: the conversion is lossy; nothing written\n"
                ),
                "{what}"
            );
        }
        #[cfg(unix)]
        {
            let d = tree(&[
                ("lefthook.yml", "pre-commit:\n  scripts:\n    a.sh: {}\n"),
                (".lefthook/pre-commit/a.sh", "true\n"),
            ]);
            let mut o = opts(d.path());
            o.strict = true;
            let (code, text) = stderr(&snp_migrate::lefthook(&o).unwrap_err());
            assert_eq!(code, 2);
            assert!(text.contains("is not executable"), "{text}");
        }
    }

    #[test]
    fn strict_accepts_faithful_conversions() {
        let d = tree(&[("lefthook.yml", WORKED_YAML)]);
        let mut o = opts(d.path());
        o.strict = true;
        assert!(snp_migrate::lefthook(&o).is_ok());
    }

    /// The commitizen hook of a real monorepo (ADR-085): `interactive` is kept (no longer lossy), and the `{2}`
    /// placeholder inside double quotes becomes the variable without quotes of its own.
    #[test]
    fn interactive_commitizen_hook() {
        const CZ: &str = "prepare-commit-msg:\n  commands:\n    commitzen:\n      interactive: true\n      run: test -n \"{2}\" || bun x cz --hook\n      env: {LEFTHOOK: \"0\"}\n";
        let d = tree(&[("lefthook.yml", CZ)]);
        let mut o = opts(d.path());
        o.strict = true;
        let c = snp_migrate::lefthook(&o).unwrap();
        assert!(!c.lossy, "{:?}", c.report);
        let yaml = &c.config_yaml;
        assert!(yaml.contains("\n        interactive: true\n"), "{yaml}");
        assert!(
            yaml.contains("test -n \"$PRE_COMMIT_COMMIT_MSG_SOURCE\" || bun x cz --hook"),
            "{yaml}"
        );
        assert!(!yaml.contains("\"\"$PRE_COMMIT"), "{yaml}");
        assert!(yaml.contains("stages: [prepare-commit-msg]"), "{yaml}");
        // outside quotes the value keeps its own quotes
        let d = tree(&[(
            "lefthook.yml",
            "prepare-commit-msg:\n  commands:\n    a:\n      run: echo {2} '{2}'\n",
        )]);
        let c = snp_migrate::lefthook(&opts(d.path())).unwrap();
        assert!(
            c.config_yaml
                .contains("echo \"$PRE_COMMIT_COMMIT_MSG_SOURCE\" '"),
            "{}",
            c.config_yaml
        );
    }
}
