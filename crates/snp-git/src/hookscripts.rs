//! 11 §A.5.1 hook-script classifier (pure, bounded file reads: ≤ 1 MiB, multi-pattern scan; lowest class rank wins).
//! Used by snp-cmd (install/uninstall/doctor) and by snp-run's `run` hint (ADR-070).
//!
//! Owner: WP-18.

use std::fs;
use std::io::{self, Read};
use std::path::Path;

use memchr::memmem;

/// Who wrote a hook script (11 §A.5.1).
#[derive(Debug, Clone, PartialEq, Eq)]
#[non_exhaustive]
pub enum Owner {
    /// No file (`!os.path.lexists(path)`).
    Missing,
    /// A directory, FIFO, socket, device, or a symlink to one (pre-commit: `IsADirectoryError`, 03 §2.5).
    NotAFile,
    /// snp 2.x (stale: an id from [`SNP_PRIOR_IDS`]).
    Snp {
        /// The script predates the current template.
        stale: bool,
    },
    /// snp 1.x (`Generated by SNP`).
    SnpV1,
    /// pre-commit: `CURRENT_HASH` or one of its five `PRIOR_HASHES` (`install_uninstall.py:22-30`). `era` is the
    /// script shape of 11 §A.3: 3 = bash `ARGS=(` (2021-09 →), 2 = Python `ARGS = [` (2020-01 → 2021-09), 1 = Python
    /// `HOOK_TYPE = ` (2018-02 → 2020-01), `None` = none of these (pre-2018 templates).
    PreCommit {
        /// Template era.
        era: Option<u8>,
    },
    /// prek (`182c10f181da4464a3eec51b83331688`).
    Prek,
    /// lefthook (`LEFTHOOK`): a foreign script.
    Lefthook,
    /// Anything else, a dangling symlink included (not "ours" for pre-commit either, `install_uninstall.py:57`).
    Foreign,
}

/// The `# … ID:` marker of the current snp hook-script template.
pub const SNP_SCRIPT_ID: &str = "5bb9bd89cf6c92c58fee7677ceaf4fc3";

/// Ids of earlier snp 2.x templates (a template change bumps the id and moves the old one here). Empty in 2.0.0.
pub const SNP_PRIOR_IDS: &[&str] = &[];

/// `CURRENT_HASH` then `PRIOR_HASHES` of `install_uninstall.py:22-30`.
const PRE_COMMIT_IDS: [&str; 6] = [
    "138fd403232d2ddd5efb44317e38bf03",
    "4d9958c90bc262f47553e2c073f14cfe",
    "d8ee923c46731b42cd95cc869add4062",
    "49fd668cb42069aa1b6048464be5d395",
    "79f09a650522a87b0da915d0d983b2de",
    "e358c9dae00eac5d06b38dfdb1e33a8c",
];
/// prek's `CURRENT_HASH` (`prek/crates/prek/src/cli/install.rs`, `PRIOR_HASHES` is empty).
const PREK_ID: &str = "182c10f181da4464a3eec51b83331688";
/// The substring snp 1.x matched in its own template header (`# Generated by SNP (Shell Not Pass)`).
const SNP_V1_MARKER: &str = "Generated by SNP";
/// lefthook's `hookContentFingerprint` (`internal/command/lefthook.go:31`).
const LEFTHOOK_MARKER: &str = "LEFTHOOK";

/// pre-commit hook scripts are < 4 KiB; reading more changes nothing (11 §A.5.1).
const READ_CAP: u64 = 1 << 20;

fn contains(hay: &[u8], needle: &str) -> bool {
    memmem::find(hay, needle.as_bytes()).is_some()
}

/// The class of the script bytes: the lowest rank of every marker found, not the first match position (snp
/// scripts also carry the pre-commit and prek ids).
fn classify_bytes(b: &[u8]) -> Owner {
    classify_bytes_with(b, SNP_PRIOR_IDS)
}

/// [`classify_bytes`] with an explicit list of earlier snp template ids (a stale script needs one; 2.0.0 has none).
fn classify_bytes_with(b: &[u8], prior_ids: &[&str]) -> Owner {
    if contains(b, SNP_SCRIPT_ID) {
        return Owner::Snp { stale: false };
    }
    if prior_ids.iter().any(|id| contains(b, id)) {
        return Owner::Snp { stale: true };
    }
    if contains(b, SNP_V1_MARKER) {
        return Owner::SnpV1;
    }
    if PRE_COMMIT_IDS.iter().any(|id| contains(b, id)) {
        let era = if contains(b, "ARGS=(") {
            Some(3)
        } else if contains(b, "ARGS = [") {
            Some(2)
        } else if contains(b, "HOOK_TYPE = ") {
            Some(1)
        } else {
            None
        };
        return Owner::PreCommit { era };
    }
    if contains(b, PREK_ID) {
        return Owner::Prek;
    }
    if contains(b, LEFTHOOK_MARKER) {
        return Owner::Lefthook;
    }
    Owner::Foreign
}

/// Classifies the hook script at `path` (≤ 1 MiB read).
///
/// `symlink_metadata` decides `Missing` (like `os.path.lexists`, a path below a non-directory is missing too);
/// symlinks are followed (a dangling or looping one is `Foreign`); anything that is not a regular file is `NotAFile`
/// and never read. The file is opened non-blocking and re-checked on the open handle, so a FIFO swapped in after
/// the `stat` can neither block the open nor be read. Read errors of a regular file (permissions) are returned.
pub fn classify(path: &Path) -> io::Result<Owner> {
    let lmd = match fs::symlink_metadata(path) {
        Ok(m) => m,
        Err(e) if is_absent(&e) => return Ok(Owner::Missing),
        Err(e) => return Err(e),
    };
    let md = if lmd.file_type().is_symlink() {
        match fs::metadata(path) {
            Ok(m) => m,
            Err(_) => return Ok(Owner::Foreign), // dangling or a loop: os.path.exists() is False
        }
    } else {
        lmd
    };
    if !md.is_file() {
        return Ok(Owner::NotAFile);
    }
    let file = open_nonblocking(path)?;
    if !file.metadata()?.is_file() {
        return Ok(Owner::NotAFile);
    }
    let mut bytes = Vec::new();
    file.take(READ_CAP).read_to_end(&mut bytes)?;
    Ok(classify_bytes(&bytes))
}

/// `os.path.lexists` is False for `ENOENT` and for `ENOTDIR` (a path component is a regular file).
fn is_absent(e: &io::Error) -> bool {
    matches!(
        e.kind(),
        io::ErrorKind::NotFound | io::ErrorKind::NotADirectory
    )
}

/// `O_NONBLOCK` of the target's libc (std opens with `O_CLOEXEC` already); `0` where it is not known here, which
/// leaves only the handle check (checked against `rustix` by this module's tests).
#[cfg(unix)]
const O_NONBLOCK: i32 = if cfg!(any(
    target_os = "macos",
    target_os = "ios",
    target_os = "tvos",
    target_os = "watchos",
    target_os = "visionos",
    target_os = "freebsd",
    target_os = "openbsd",
    target_os = "netbsd",
    target_os = "dragonfly",
)) {
    0x0004
} else if cfg!(all(
    any(target_os = "linux", target_os = "android"),
    not(any(
        target_arch = "mips",
        target_arch = "mips32r6",
        target_arch = "mips64",
        target_arch = "mips64r6",
        target_arch = "sparc",
        target_arch = "sparc64"
    ))
)) {
    0o4000
} else {
    0
};

/// `open(path, O_RDONLY | O_NONBLOCK | O_CLOEXEC)`: never blocks on a FIFO or a device.
#[cfg(unix)]
fn open_nonblocking(path: &Path) -> io::Result<fs::File> {
    use std::os::unix::fs::OpenOptionsExt;
    fs::OpenOptions::new()
        .read(true)
        .custom_flags(O_NONBLOCK)
        .open(path)
}

/// Windows has no FIFOs in the file namespace: a plain read-only open.
#[cfg(not(unix))]
fn open_nonblocking(path: &Path) -> io::Result<fs::File> {
    fs::File::open(path)
}

impl Owner {
    /// A hook manager's script (overwritten in place by `snp install`): snp, snp 1.x, pre-commit, prek.
    pub fn is_manager(&self) -> bool {
        matches!(
            self,
            Self::Snp { .. } | Self::SnpV1 | Self::PreCommit { .. } | Self::Prek
        )
    }

    /// "pre-commit" | "prek" | "snp 1.x" — the `{owner}` of the M1/M2/M3 notes (11 §A.5.4); `snp` for snp's own
    /// script (M12 wording); `None` for non-managers.
    pub fn owner_name(&self) -> Option<&'static str> {
        match self {
            Self::PreCommit { .. } => Some("pre-commit"),
            Self::Prek => Some("prek"),
            Self::SnpV1 => Some("snp 1.x"),
            Self::Snp { .. } => Some("snp"),
            Self::Missing | Self::NotAFile | Self::Lefthook | Self::Foreign => None,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The open used after the `stat` never blocks on a FIFO (a writer-less FIFO blocks a plain `open(2)` forever),
    /// and the handle check sees it is not a regular file.
    #[test]
    #[cfg(unix)]
    fn o_nonblock_is_the_libc_value() {
        let want = rustix::fs::OFlags::NONBLOCK.bits();
        assert_eq!(u32::try_from(O_NONBLOCK).unwrap(), want);
    }

    #[test]
    #[cfg(unix)]
    fn the_handle_open_never_blocks_on_a_fifo() {
        let d = tempfile::tempdir().unwrap();
        let fifo = d.path().join("fifo");
        let st = std::process::Command::new("mkfifo").arg(&fifo).status();
        if !st.is_ok_and(|s| s.success()) {
            return;
        }
        let f = open_nonblocking(&fifo).unwrap();
        assert!(!f.metadata().unwrap().is_file());
        let reg = d.path().join("reg");
        fs::write(&reg, b"#!/bin/sh\n").unwrap();
        let mut text = String::new();
        open_nonblocking(&reg)
            .unwrap()
            .read_to_string(&mut text)
            .unwrap();
        assert_eq!(text, "#!/bin/sh\n");
    }

    #[test]
    fn rank_beats_position() {
        let snp = format!(
            "#!/bin/sh\n# pre-commit compat ID: {}\n# prek compat ID: {PREK_ID}\n# ID: {SNP_SCRIPT_ID}\n",
            PRE_COMMIT_IDS[0]
        );
        assert_eq!(classify_bytes(snp.as_bytes()), Owner::Snp { stale: false });
        assert_eq!(
            classify_bytes(format!("x {PREK_ID} LEFTHOOK").as_bytes()),
            Owner::Prek
        );
        assert_eq!(classify_bytes(b"$LEFTHOOK"), Owner::Lefthook);
        assert_eq!(classify_bytes(b"#!/bin/sh\nexit 0\n"), Owner::Foreign);
        assert_eq!(
            classify_bytes(
                b"# Generated by SNP (Shell Not Pass)\n# 138fd403232d2ddd5efb44317e38bf03"
            ),
            Owner::SnpV1
        );
    }

    #[test]
    fn stale_snp_scripts() {
        // A template change moves the current id into SNP_PRIOR_IDS; such a script is a stale snp script, which
        // still outranks the pre-commit/prek compat ids it carries.
        let old = "0123456789abcdef0123456789abcdef";
        let script = format!(
            "# ID: {old}\n# pre-commit compat ID: {}\n",
            PRE_COMMIT_IDS[0]
        );
        assert_eq!(
            classify_bytes_with(script.as_bytes(), &[old]),
            Owner::Snp { stale: true }
        );
        assert_eq!(
            classify_bytes_with(script.as_bytes(), &[]),
            Owner::PreCommit { era: None }
        );
        let both = format!("{script}# ID: {SNP_SCRIPT_ID}\n");
        assert_eq!(
            classify_bytes_with(both.as_bytes(), &[old]),
            Owner::Snp { stale: false }
        );
        assert!(SNP_PRIOR_IDS.is_empty(), "2.0.0 ships no earlier template");
    }

    #[test]
    fn names_and_managers() {
        assert_eq!(
            Owner::PreCommit { era: Some(3) }.owner_name(),
            Some("pre-commit")
        );
        assert_eq!(Owner::Prek.owner_name(), Some("prek"));
        assert_eq!(Owner::SnpV1.owner_name(), Some("snp 1.x"));
        assert_eq!(Owner::Snp { stale: true }.owner_name(), Some("snp"));
        for o in [
            Owner::Missing,
            Owner::NotAFile,
            Owner::Lefthook,
            Owner::Foreign,
        ] {
            assert_eq!(o.owner_name(), None);
            assert!(!o.is_manager());
        }
        assert!(Owner::Snp { stale: false }.is_manager());
        assert!(Owner::SnpV1.is_manager());
        assert!(Owner::PreCommit { era: None }.is_manager());
        assert!(Owner::Prek.is_manager());
    }
}
