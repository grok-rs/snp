"""Generate ``src/py/tables.rs`` from the running CPython's Unicode database.

Usage (from any directory that contains no ``.py`` files)::

    python3.12 -I scripts/gen_unicode_tables.py src/py/tables.rs

The table pins the behaviour of ``str.isprintable()`` (and therefore of
``repr(str)``) to the Unicode database of the interpreter that ran this
script.  cfgv pins CPython 3.12 / Unicode 15.0.0; pass ``--allow-any-version``
to regenerate from another interpreter on purpose.

Only the standard library is used and nothing is imported from the
repository, so the script is safe to run with ``-I``.
"""
from __future__ import annotations

import sys
import unicodedata

EXPECTED_UNICODE = '15.0.0'


def nonprintable_ranges() -> list[tuple[int, int]]:
    ranges: list[tuple[int, int]] = []
    start = None
    for cp in range(0x80, sys.maxunicode + 1):
        printable = chr(cp).isprintable()
        if not printable and start is None:
            start = cp
        elif printable and start is not None:
            ranges.append((start, cp - 1))
            start = None
    if start is not None:
        ranges.append((start, sys.maxunicode))
    return ranges


def main() -> int:
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    allow_any = '--allow-any-version' in sys.argv
    if len(args) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    version = unicodedata.unidata_version
    if version != EXPECTED_UNICODE and not allow_any:
        print(
            f'refusing to generate from Unicode {version}; '
            f'expected {EXPECTED_UNICODE} (CPython 3.12)',
            file=sys.stderr,
        )
        return 1

    # Sanity checks of the assumptions the Rust side relies on.
    for cp in range(0x80):
        assert chr(cp).isprintable() == (0x20 <= cp < 0x7f), cp

    ranges = nonprintable_ranges()
    impl = sys.implementation
    py = f'{impl.name} {sys.version_info.major}.{sys.version_info.minor}'
    lines = [
        '// @generated by scripts/gen_unicode_tables.py -- do not edit.',
        f'// Source: {py}, Unicode {version}.',
        '',
        '/// Version of the Unicode database the tables were generated from.',
        f'pub(crate) const UNICODE_VERSION: &str = "{version}";',
        '',
        '/// Sorted, disjoint, inclusive code point ranges at or above U+0080',
        '/// for which CPython\'s `str.isprintable()` is `False`.',
        '#[rustfmt::skip]',
        '#[allow(clippy::unreadable_literal)]',
        'pub(crate) static NONPRINTABLE: &[(u32, u32)] = &[',
    ]
    for lo, hi in ranges:
        lines.append(f'    (0x{lo:04X}, 0x{hi:04X}),')
    lines.append('];')
    with open(args[0], 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'wrote {len(ranges)} ranges to {args[0]}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
