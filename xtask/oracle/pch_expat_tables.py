"""snp-pyparsers `xml` tables (WP-17): expat's Name character classes and the single-byte codecs pyexpat's
unknown-encoding handler builds from Python, written as Rust to crates/snp-pyparsers/src/xml/generated.rs.

Run by `cargo xtask gen-pch-data vectors` under both pch oracles (the system expat): the Name classes are expat's
`nmstrtPages`/`namePages` bitmaps, probed through pyexpat for every BMP code point (`names.rs`), and the codec
tables are `bytes(range(256)).decode(name, 'replace')` as pyexpat's PyUnknownEncodingHandler does it
(`codecs_3XX.rs`; the `encodings` package differs between minors).

usage: python -I pch_expat_tables.py OUTDIR
"""
from __future__ import annotations

import encodings
import encodings.aliases
import pkgutil
import sys
import warnings
import xml.parsers.expat as expat


def ok(doc: bytes) -> bool:
    p = expat.ParserCreate()
    try:
        p.Parse(doc, True)
    except expat.ExpatError:
        return False
    return True


def ranges(pred) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for cp in range(0x80, 0x10000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        if pred(cp):
            if out and out[-1][1] == cp - 1:
                out[-1] = (out[-1][0], cp)
            else:
                out.append((cp, cp))
    return out


def codec_kind(name: str):
    try:
        with warnings.catch_warnings():
            warnings.simplefilter('ignore')
            u = bytes(range(256)).decode(name, 'replace')
    except LookupError as exc:
        if str(exc) == f'unknown encoding: {name}':
            return None
        return ('error', 'LookupError', str(exc))
    except Exception as exc:  # noqa: BLE001 - recorded as the crash pyexpat propagates
        return ('error', type(exc).__name__, str(exc))
    if not isinstance(u, str):
        return ('error', 'TypeError', 'not a str')
    if len(u) != 256:
        return ('multibyte',)
    return ('table', tuple(-1 if ch == '�' else ord(ch) for ch in u))


def main() -> int:
    outdir = sys.argv[1]
    minor = f'{sys.version_info[0]}{sys.version_info[1]}'
    nmstrt = ranges(lambda cp: ok(f'<{chr(cp)}/>'.encode()))
    name = ranges(lambda cp: ok(f'<a{chr(cp)}/>'.encode()))
    modules = sorted({m.name for m in pkgutil.iter_modules(encodings.__path__)} - {'aliases'})
    kinds = {}
    for m in modules:
        k = codec_kind(m)
        if k is not None:
            kinds[m] = k
    aliases = sorted((a, t) for a, t in encodings.aliases.aliases.items())
    tables: list[tuple[int, ...]] = []
    head = [
        '//! Generated by `xtask/oracle/pch_expat_tables.py` (`cargo xtask gen-pch-data vectors`); do not edit.',
        '//!',
        '//! Owner: WP-17.',
        '',
    ]
    lines = head + [
        f'/// expat\'s version (`pyexpat.EXPAT_VERSION`) the classes were probed from.',
        f'pub(crate) const EXPAT_VERSION: &str = "{expat.EXPAT_VERSION}";',
        '',
        '/// Code points ≥ U+0080 that start an expat `Name` (`nmstrtPages`), as inclusive ranges.',
        'pub(crate) const NMSTRT: &[(u16, u16)] = &[',
    ]
    lines += [f'    (0x{a:04X}, 0x{b:04X}),' for a, b in nmstrt]
    lines += ['];', '', '/// Code points ≥ U+0080 that continue an expat `Name` (`namePages`), as inclusive ranges.',
              'pub(crate) const NAME: &[(u16, u16)] = &[']
    lines += [f'    (0x{a:04X}, 0x{b:04X}),' for a, b in name]
    lines += ['];', '']
    with open(f'{outdir}/names.rs', 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    lines = head + ['use super::super::Codec;', '']
    entries = []
    for m in modules:
        k = kinds.get(m)
        if k is None:
            continue
        if k[0] == 'table':
            t = k[1]
            if t not in tables:
                tables.append(t)
            entries.append(f'    ("{m}", Codec::Table({tables.index(t)})),')
        elif k[0] == 'multibyte':
            entries.append(f'    ("{m}", Codec::MultiByte),')
        else:
            ty, msg = k[1], k[2].replace('\\', '\\\\').replace('"', '\\"')
            entries.append(f'    ("{m}", Codec::Error("{ty}", "{msg}")),')
    lines += ['/// How `bytes(range(256)).decode(module)` behaves for each module of the `encodings` package.',
              'pub(crate) const MODULES: &[(&str, Codec)] = &[']
    lines += entries
    lines += ['];', '', '/// `encodings.aliases.aliases`.', 'pub(crate) const ALIASES: &[(&str, &str)] = &[']
    lines += [f'    ("{a}", "{t}"),' for a, t in aliases]
    lines += ['];', '', '/// The distinct 256-entry tables (`-1`: undecodable byte).',
              f'pub(crate) const TABLES: &[[i32; 256]; {len(tables)}] = &[']
    for t in tables:
        lines.append('    [')
        for i in range(0, 256, 16):
            lines.append('        ' + ', '.join(str(x) for x in t[i:i + 16]) + ',')
        lines.append('    ],')
    lines += ['];', '']
    out = f'{outdir}/codecs_{minor}.rs'
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print(f'wrote {out}: {len(nmstrt)} + {len(name)} name ranges, {len(entries)} codecs, {len(tables)} tables',
          file=sys.stderr)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
