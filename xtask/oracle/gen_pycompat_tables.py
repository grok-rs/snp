"""Emit Rust tables for snp-pycompat from the running CPython's unicodedata.

    /usr/bin/python3.13 -I xtask/oracle/gen_pycompat_tables.py crates/snp-pycompat/src/generated/tables.rs

Run under CPython 3.13 (UCD 15.1, ADR-020). Vendored from docs/research/scripts/gen_pycompat_tables.py
by WP-00 and extended with the east-asian-width table (`_len_cjk`, 02 §13.1) and lint-clean literal
formatting; owned by WP-11 afterwards.
"""
import sys
import unicodedata

out = sys.argv[1]


def ranges(pred):
    rs, start = [], None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            rs.append((start, cp - 1))
            start = None
    if start is not None:
        rs.append((start, 0x10FFFF))
    return rs


def lit(cp):
    """A hex literal grouped by 4 nibbles (clippy `unreadable_literal`)."""
    h = '%04X' % cp
    groups = []
    while len(h) > 4:
        groups.insert(0, h[-4:])
        h = h[:-4]
    groups.insert(0, h)
    return '0x' + '_'.join(groups)


# repr() keeps non-ASCII code points that are printable; we store the
# complement (non-printable) for code points >= 0x80 only.
nonprint = ranges(lambda cp: cp >= 0x80 and not chr(cp).isprintable())
zeros = [cp for cp in range(0x110000) if unicodedata.decimal(chr(cp), None) == 0]
for z in zeros:  # every Nd run is 10 contiguous digits starting at a zero
    assert all(unicodedata.decimal(chr(z + i), None) == i for i in range(10)), hex(z)
ndigits = sum(1 for cp in range(0x110000) if unicodedata.decimal(chr(cp), None) is not None)
assert ndigits == 10 * len(zeros), (ndigits, len(zeros))
# `pre_commit.commands.run._len_cjk`: east_asian_width W and F count 2 columns.
wide = ranges(lambda cp: unicodedata.east_asian_width(chr(cp)) in ('W', 'F'))

with open(out, 'w', newline='\n') as f:
    f.write('// @generated by xtask/oracle/gen_pycompat_tables.py from CPython %s '
            '(Unicode %s). Do not edit.\n' % (sys.version.split()[0], unicodedata.unidata_version))
    f.write('\n')
    f.write('/// Unicode version of the CPython `unicodedata` these tables were generated from.\n')
    f.write('pub(crate) const UNICODE_VERSION: &str = "%s";\n' % unicodedata.unidata_version)
    f.write('\n')
    f.write('/// Inclusive code point ranges >= U+0080 for which `str.isprintable()` is False.\n')
    f.write('pub(crate) static NONPRINTABLE: &[(u32, u32)] = &[\n')
    for a, b in nonprint:
        f.write('    (%s, %s),\n' % (lit(a), lit(b)))
    f.write('];\n')
    f.write('\n')
    f.write('/// Code points with `unicodedata.decimal(c) == 0`; each starts a run of 10 digits.\n')
    f.write('pub(crate) static DECIMAL_ZEROS: &[u32] = &[\n')
    for z in zeros:
        f.write('    %s,\n' % lit(z))
    f.write('];\n')
    f.write('\n')
    f.write('/// Inclusive code point ranges whose `unicodedata.east_asian_width` is `W` or `F`.\n')
    f.write('pub(crate) static EAST_ASIAN_WIDE: &[(u32, u32)] = &[\n')
    for a, b in wide:
        f.write('    (%s, %s),\n' % (lit(a), lit(b)))
    f.write('];\n')
print('ranges', len(nonprint), 'zeros', len(zeros), 'wide', len(wide))
